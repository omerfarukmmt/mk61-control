for _i in range(26):
    NAMES[0x04 + _i] = chr(65 + _i)
for _i in range(1, 10):
    NAMES[0x1D + _i] = str(_i)
NAMES[0x27] = "0"
for _i in range(12):
    NAMES[0x3A + _i] = f"F{_i + 1}"
for _i, _n in enumerate(["Left Ctrl", "Left Shift", "Left Alt", "Left Win",
                         "Right Ctrl", "Right Shift", "Right Alt", "Right Win"]):
    NAMES[0xE0 + _i] = _n


def name(code: int) -> str:
    return NAMES.get(code, f"0x{code:02X}")


